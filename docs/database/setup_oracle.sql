-- =============================================================
-- CREATE TB_CONVERSA
-- Estado da conversa omnichannel.
--
-- Regra critica:
-- - cadastro aponta para pessoa;
-- - acomp_paciente aponta para paciente;
-- - acomp_dentista aponta para dentista;
-- - apenas um vinculo contextual pode estar preenchido.
-- =============================================================

CREATE TABLE TB_CONVERSA (
                             ID_CONVERSA     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             CANAL_CONV      VARCHAR2(20) DEFAULT 'telegram' NOT NULL,
                             CONTEXTO        VARCHAR2(20) NOT NULL,
                             TG_THREAD_ID    VARCHAR2(120),
                             ID_PESSOA       NUMBER,
                             ID_PACIENTE     NUMBER,
                             ID_DENTISTA     NUMBER,
                             STTS_CONV       VARCHAR2(15) DEFAULT 'aberta' NOT NULL,
                             NAO_LIDAS       NUMBER(5) DEFAULT 0 NOT NULL,
                             DATA_CRIACAO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                             DATA_ATUALIZACAO TIMESTAMP,

                             CONSTRAINT FK_CONV_PESS FOREIGN KEY (ID_PESSOA)
                                 REFERENCES TB_PESSOA(ID_PESSOA),

                             CONSTRAINT FK_CONV_PAC FOREIGN KEY (ID_PACIENTE)
                                 REFERENCES TB_PACIENTE(ID_PACIENTE),

                             CONSTRAINT FK_CONV_DENT FOREIGN KEY (ID_DENTISTA)
                                 REFERENCES TB_DENTISTA(ID_DENTISTA),

                             CONSTRAINT CHK_CONV_CANAL CHECK (CANAL_CONV IN ('telegram','web','whatsapp','manual')),
                             CONSTRAINT CHK_CONV_STATUS CHECK (STTS_CONV IN ('aberta','fechada','arquivada')),
                             CONSTRAINT CHK_CONV_NLIDAS CHECK (NAO_LIDAS >= 0),

                             CONSTRAINT CHK_CONV_CTX_FK CHECK (
                                 (CONTEXTO = 'cadastro'
                                     AND ID_PESSOA IS NOT NULL
                                     AND ID_PACIENTE IS NULL
                                     AND ID_DENTISTA IS NULL)
                                     OR
                                 (CONTEXTO = 'acomp_paciente'
                                     AND ID_PESSOA IS NULL
                                     AND ID_PACIENTE IS NOT NULL
                                     AND ID_DENTISTA IS NULL)
                                     OR
                                 (CONTEXTO = 'acomp_dentista'
                                     AND ID_PESSOA IS NULL
                                     AND ID_PACIENTE IS NULL
                                     AND ID_DENTISTA IS NOT NULL)
                                 )
);


