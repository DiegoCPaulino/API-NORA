-- =============================================================
-- CREATE TB_ENDERECO
-- Enderecos de pessoas e dentistas.
-- Latitude/longitude sao opcionais para cenarios com geocodificacao.
-- =============================================================

CREATE TABLE TB_ENDERECO (
                             ID_ENDERECO     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             CEP             VARCHAR2(8)   NOT NULL,
                             LOGRADOURO      VARCHAR2(150) NOT NULL,
                             NUMERO          VARCHAR2(15)  NOT NULL,
                             COMPLEMENTO     VARCHAR2(60),
                             BAIRRO          VARCHAR2(80)  NOT NULL,
                             CIDADE          VARCHAR2(80)  NOT NULL,
                             UF              VARCHAR2(2)   NOT NULL,
                             LATITUDE        NUMBER(10,7),
                             LONGITUDE       NUMBER(10,7),
                             DATA_CRIACAO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

                             CONSTRAINT CHK_END_CEP CHECK (LENGTH(CEP) = 8),
                             CONSTRAINT CHK_END_UF CHECK (LENGTH(UF) = 2)
);


-- =============================================================
-- CREATE TB_COLABORADOR
-- Funcionarios internos para login e operacao do sistema.
-- Senha armazenada como hash/texto tecnico para ambiente academico.
-- =============================================================

CREATE TABLE TB_COLABORADOR (
                                ID_COLABORADOR  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                NOME            VARCHAR2(120) NOT NULL,
                                EMAIL           VARCHAR2(120) NOT NULL UNIQUE,
                                SENHA_HASH      VARCHAR2(255) NOT NULL,
                                PERFIL          VARCHAR2(20)  DEFAULT 'atendente' NOT NULL,
                                STATUS_COLAB    VARCHAR2(10)  DEFAULT 'ativo' NOT NULL,
                                DATA_CRIACAO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

                                CONSTRAINT CHK_COLAB_PERFIL CHECK (PERFIL IN ('admin','atendente','gestor')),
                                CONSTRAINT CHK_COLAB_STATUS CHECK (STATUS_COLAB IN ('ativo','inativo'))
);


-- =============================================================
-- CREATE TB_COLABORADOR_SESSAO
-- Controle simples de sessao/token opaco.
-- Alternativa academica mais simples do que JWT completo.
-- =============================================================

CREATE TABLE TB_COLABORADOR_SESSAO (
                                       ID_SESSAO       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       ID_COLABORADOR  NUMBER NOT NULL,
                                       TOKEN           VARCHAR2(120) NOT NULL UNIQUE,
                                       DATA_CRIACAO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                                       DATA_EXPIRACAO  TIMESTAMP NOT NULL,
                                       STATUS_SESSAO   VARCHAR2(10) DEFAULT 'ativo' NOT NULL,

                                       CONSTRAINT FK_SESSAO_COLAB FOREIGN KEY (ID_COLABORADOR)
                                           REFERENCES TB_COLABORADOR(ID_COLABORADOR),

                                       CONSTRAINT CHK_SESSAO_STATUS CHECK (STATUS_SESSAO IN ('ativo','inativo','expirada'))
);


-- =============================================================
-- CREATE TB_PESSOA
-- Lead/cadastro inicial vindo do bot, N8N, frontend ou cadastro manual.
-- Regra de negocio: Projeto Nora atende adolescentes de 11 a 17 anos.
-- =============================================================

CREATE TABLE TB_PESSOA (
                           ID_PESSOA       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           ID_ENDERECO     NUMBER NOT NULL,
                           NOME_COMPLETO   VARCHAR2(120) NOT NULL,
                           CPF             VARCHAR2(11) UNIQUE,
                           DATA_NASCIMENTO DATE NOT NULL,
                           IDADE           NUMBER(3) NOT NULL,
                           SEXO            VARCHAR2(1),
                           EMAIL           VARCHAR2(120),
                           TELEFONE        VARCHAR2(20) NOT NULL,
                           TG_CHAT_ID      VARCHAR2(80),
                           CANAL_ORIG      VARCHAR2(20) DEFAULT 'telegram' NOT NULL,
                           STTS_PESS       VARCHAR2(20) DEFAULT 'lead' NOT NULL,
                           DATA_CRIACAO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                           DATA_ATUALIZACAO TIMESTAMP,

                           CONSTRAINT FK_PESS_END FOREIGN KEY (ID_ENDERECO)
                               REFERENCES TB_ENDERECO(ID_ENDERECO),

                           CONSTRAINT CHK_PESS_IDADE CHECK (IDADE BETWEEN 11 AND 17),
                           CONSTRAINT CHK_PESS_SEXO CHECK (SEXO IS NULL OR SEXO IN ('M','F','O')),
                           CONSTRAINT CHK_PESS_CANAL CHECK (CANAL_ORIG IN ('telegram','web','manual','n8n')),
                           CONSTRAINT CHK_PESS_STATUS CHECK (STTS_PESS IN ('lead','em_triagem','aprovada','reprovada','inativa'))
);


-- =============================================================
-- CREATE TB_TRIAGEM
-- Avaliacao de elegibilidade, urgencia e prioridade.
-- Campos NIVEL_URG_IA e CONF_IA sustentam integracao com Python/ML.
-- =============================================================

CREATE TABLE TB_TRIAGEM (
                            ID_TRIAGEM      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            ID_PESSOA       NUMBER NOT NULL,
                            IDADE           NUMBER(3) NOT NULL,
                            ELEG_TRIAG      VARCHAR2(12) NOT NULL,
                            PRIOR_TRIAG     VARCHAR2(10) NOT NULL,
                            SEXO_PESS       VARCHAR2(1),
                            PROBLEMA_BUCAL  VARCHAR2(300) NOT NULL,
                            RENDA_FAMILIAR  VARCHAR2(20) NOT NULL,
                            NIVEL_URG_IA    NUMBER(3,1),
                            CONF_IA         NUMBER(5,2),
                            STTS_TRIAG      VARCHAR2(15) DEFAULT 'em_analise' NOT NULL,
                            DECISAO         VARCHAR2(15) DEFAULT 'pendente' NOT NULL,
                            OBSERVACOES     VARCHAR2(300),
                            DATA_CRIACAO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                            DATA_ATUALIZACAO TIMESTAMP,

                            CONSTRAINT FK_TRIAG_PESS FOREIGN KEY (ID_PESSOA)
                                REFERENCES TB_PESSOA(ID_PESSOA),

                            CONSTRAINT CHK_TRIAG_IDADE CHECK (IDADE BETWEEN 11 AND 17),
                            CONSTRAINT CHK_TRIAG_ELEG CHECK (ELEG_TRIAG IN ('elegivel','inelegivel')),
                            CONSTRAINT CHK_TRIAG_PRIOR CHECK (PRIOR_TRIAG IN ('baixa','media','alta','urgente')),
                            CONSTRAINT CHK_TRIAG_SEXO CHECK (SEXO_PESS IS NULL OR SEXO_PESS IN ('M','F','O')),
                            CONSTRAINT CHK_TRIAG_RENDA CHECK (RENDA_FAMILIAR IN ('ate_1sm','1_3sm','acima_3sm','nao_informada')),
                            CONSTRAINT CHK_TRIAG_IA CHECK (NIVEL_URG_IA IS NULL OR NIVEL_URG_IA BETWEEN 0 AND 5),
                            CONSTRAINT CHK_TRIAG_CONF CHECK (CONF_IA IS NULL OR CONF_IA BETWEEN 0 AND 100),
                            CONSTRAINT CHK_TRIAG_STATUS CHECK (STTS_TRIAG IN ('em_analise','aprovada','reprovada','cancelada')),
                            CONSTRAINT CHK_TRIAG_DEC CHECK (DECISAO IN ('pendente','aprovado','reprovado','cancelado'))
);


