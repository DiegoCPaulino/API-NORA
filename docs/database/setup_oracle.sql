-- =============================================================
-- CREATE TB_DENTISTA
-- Dentistas voluntarios disponiveis para encaminhamento.
-- Regra principal: disponivel quando STTS_DENT = ativo e ATIVOS < CAP_MENSAL.
-- =============================================================

CREATE TABLE TB_DENTISTA (
                             ID_DENTISTA     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             ID_ENDERECO     NUMBER NOT NULL,
                             NOME            VARCHAR2(120) NOT NULL,
                             CRO             VARCHAR2(20) NOT NULL UNIQUE,
                             EMAIL           VARCHAR2(120),
                             TELEFONE        VARCHAR2(20) NOT NULL,
                             STTS_DENT       VARCHAR2(10) DEFAULT 'ativo' NOT NULL,
                             CAP_MENSAL      NUMBER(3) DEFAULT 0 NOT NULL,
                             ATIVOS          NUMBER(3) DEFAULT 0 NOT NULL,
                             DATA_CADASTRO   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                             OBSERVACOES     VARCHAR2(300),

                             CONSTRAINT FK_DENT_END FOREIGN KEY (ID_ENDERECO)
                                 REFERENCES TB_ENDERECO(ID_ENDERECO),

                             CONSTRAINT CHK_DENT_STATUS CHECK (STTS_DENT IN ('ativo','inativo')),
                             CONSTRAINT CHK_DENT_CAP CHECK (CAP_MENSAL >= 0),
                             CONSTRAINT CHK_DENT_ATIVOS CHECK (ATIVOS >= 0),
                             CONSTRAINT CHK_DENT_CAP_ATV CHECK (ATIVOS <= CAP_MENSAL)
);


