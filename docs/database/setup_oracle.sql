UNION ALL
SELECT 'TB_CONVERSA', COUNT(*) FROM TB_CONVERSA
UNION ALL
SELECT 'TB_MENSAGEM', COUNT(*) FROM TB_MENSAGEM
UNION ALL
SELECT 'TB_ACOMP_EVENTO', COUNT(*) FROM TB_ACOMP_EVENTO;


-- 2. Listar triagens por status
SELECT STTS_TRIAG, COUNT(*) AS TOTAL
FROM TB_TRIAGEM
GROUP BY STTS_TRIAG
ORDER BY STTS_TRIAG;


-- 3. Listar dentistas disponiveis
SELECT
    D.ID_DENTISTA,
    D.NOME,
    D.CRO,
    D.STTS_DENT,
    D.CAP_MENSAL,
    D.ATIVOS,
    E.BAIRRO,
    E.CIDADE,
    E.UF
FROM TB_DENTISTA D
         JOIN TB_ENDERECO E ON E.ID_ENDERECO = D.ID_ENDERECO
WHERE D.STTS_DENT = 'ativo'
  AND D.ATIVOS < D.CAP_MENSAL;


-- 4. Listar conversas por contexto
SELECT CONTEXTO, COUNT(*) AS TOTAL
FROM TB_CONVERSA
GROUP BY CONTEXTO
ORDER BY CONTEXTO;


-- 5. Listar encaminhamentos ativos
SELECT
    ENC.ID_ENCAMINHAMENTO,
    P.NOME_COMPLETO AS PACIENTE,
    D.NOME AS DENTISTA,
    ENC.STTS_ENCAM,
    ENC.PRIORIDADE,
    ENC.MATCH_AUTO,
    ENC.DIST_KM,
    ENC.PREV_FOLLOW
FROM TB_ENCAMINHAMENTO ENC
         JOIN TB_PACIENTE PAC ON PAC.ID_PACIENTE = ENC.ID_PACIENTE
         JOIN TB_PESSOA P ON P.ID_PESSOA = PAC.ID_PESSOA
         JOIN TB_DENTISTA D ON D.ID_DENTISTA = ENC.ID_DENTISTA
WHERE ENC.STTS_ENCAM = 'ativo';


-- 6. Testar relacionamento pessoa -> triagem
SELECT
    P.ID_PESSOA,
    P.NOME_COMPLETO,
    P.STTS_PESS,
    T.ID_TRIAGEM,
    T.ELEG_TRIAG,
    T.PRIOR_TRIAG,
    T.STTS_TRIAG,
    T.DECISAO
FROM TB_PESSOA P
         LEFT JOIN TB_TRIAGEM T ON T.ID_PESSOA = P.ID_PESSOA
ORDER BY P.ID_PESSOA;


-- 7. Testar relacionamento paciente -> encaminhamento -> dentista
SELECT
    PAC.ID_PACIENTE,
    P.NOME_COMPLETO AS PACIENTE,
    PAC.STTS_TRAT,
    ENC.ID_ENCAMINHAMENTO,
    ENC.STTS_ENCAM,
    D.NOME AS DENTISTA,
    D.CRO
FROM TB_PACIENTE PAC
         JOIN TB_PESSOA P ON P.ID_PESSOA = PAC.ID_PESSOA
         LEFT JOIN TB_ENCAMINHAMENTO ENC ON ENC.ID_PACIENTE = PAC.ID_PACIENTE
         LEFT JOIN TB_DENTISTA D ON D.ID_DENTISTA = ENC.ID_DENTISTA;


-- 8. Testar mensagens por conversa
SELECT
    C.ID_CONVERSA,
    C.CONTEXTO,
    C.TG_THREAD_ID,
    M.ID_MENSAGEM,
    M.ENVIADO_POR,
    M.DIRECAO,
    M.TIPO_MENSAGEM,
    M.CONTEUDO,
    M.LIDA,
    M.DATA_ENVIO
FROM TB_CONVERSA C
         JOIN TB_MENSAGEM M ON M.ID_CONVERSA = C.ID_CONVERSA
ORDER BY C.ID_CONVERSA, M.DATA_ENVIO;


-- 9. Testar eventos por encaminhamento
SELECT
    ENC.ID_ENCAMINHAMENTO,
    P.NOME_COMPLETO AS PACIENTE,
    D.NOME AS DENTISTA,
    EV.TIPO_EVENTO,
    EV.ORIGEM,
    EV.DS_EVENTO,
    EV.DATA_EVENTO
FROM TB_ACOMP_EVENTO EV
         JOIN TB_ENCAMINHAMENTO ENC ON ENC.ID_ENCAMINHAMENTO = EV.ID_ENCAMINHAMENTO
         JOIN TB_PACIENTE PAC ON PAC.ID_PACIENTE = ENC.ID_PACIENTE
         JOIN TB_PESSOA P ON P.ID_PESSOA = PAC.ID_PESSOA
         JOIN TB_DENTISTA D ON D.ID_DENTISTA = ENC.ID_DENTISTA;


-- 10. Metricas basicas para dashboard
SELECT COUNT(*) AS TOTAL_LEADS FROM TB_PESSOA;

SELECT COUNT(*) AS TOTAL_PACIENTES FROM TB_PACIENTE;

SELECT COUNT(*) AS TOTAL_ENCAMINHAMENTOS_ATIVOS
FROM TB_ENCAMINHAMENTO
WHERE STTS_ENCAM = 'ativo';

SELECT CANAL_ORIG, COUNT(*) AS TOTAL
FROM TB_PESSOA
GROUP BY CANAL_ORIG;

SELECT E.BAIRRO, E.CIDADE, E.UF, COUNT(*) AS TOTAL_PESSOAS
FROM TB_PESSOA P
         JOIN TB_ENDERECO E ON E.ID_ENDERECO = P.ID_ENDERECO
GROUP BY E.BAIRRO, E.CIDADE, E.UF
ORDER BY TOTAL_PESSOAS DESC;